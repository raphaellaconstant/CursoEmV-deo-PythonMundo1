palavra = input('Digite algo: ')
print('O tipo primitivo desse valor é: {}'.format(type(palavra)))
print('Possui apenas letras? {}'.format(palavra.isalpha()))
print('É alfanumerico? {}'.format(palavra.isalnum()))
print('Está em maiusculas? {}'.format(palavra.isupper()))
print('Está minusculas? {}'.format(palavra.islower()))
print('Está capitalizada? {}'.format(palavra.istitle()))
print('So tem espaços? {}'.format(palavra.isspace()))
